/**
 * Copy text from a plain-HTTP WKWebView.
 *
 * `navigator.clipboard` only exists in secure contexts, and this app is served
 * over http:// on the LAN, so the async API is usually missing. The legacy
 * execCommand path still works when it runs inside a user gesture.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text)
      return true
    }
  } catch {
    // Fall through: permission or insecure-context failure.
  }
  try {
    const area = document.createElement('textarea')
    area.value = text
    area.setAttribute('readonly', '')
    area.style.position = 'fixed'
    area.style.top = '-1000px'
    area.style.opacity = '0'
    document.body.appendChild(area)
    area.select()
    area.setSelectionRange(0, text.length)
    const ok = document.execCommand('copy')
    area.remove()
    return ok
  } catch {
    return false
  }
}
